import { collectPdf, footerStamp, header, makePdf } from '../pdfkit.js';
import { env } from '../../config/env.js';

export async function placementLetterPdf(input: {
  studentName: string;
  studentId: string;
  organization: string;
  position: string;
  startDate: string;
  endDate: string;
  cycleTitle: string;
}) {
  const doc = makePdf();
  header(doc, 'Official placement letter', input.cycleTitle);
  doc.fontSize(11).fillColor('#222').text(
    `This letter confirms that ${input.studentName} (Student ID ${input.studentId}) is placed at ${input.organization} for the internship position “${input.position}” from ${input.startDate} to ${input.endDate}, under ${env.UNIVERSITY_NAME}.`,
  );
  doc.moveDown();
  doc.text(
    'The student is expected to keep weekly logbooks, record attendance, and follow host organization rules. Supervisors will review work on TrackBridge. This letter is generated by the system of record; it is not a grade.',
  );
  footerStamp(doc);
  return collectPdf(doc);
}
